import argparse
from model_pipeline import (
    prepare_data,
    train_model,
    evaluate_model,
    save_model,
    load_model,
)


def main():
    parser = argparse.ArgumentParser(
        description="Pipeline ML - Classification Réadmission"
    )
    parser.add_argument(
        "--data", type=str, default="diabetic_data.csv", help="Chemin du fichier CSV"
    )
    parser.add_argument(
        "--test_size", type=float, default=0.2, help="Taille du test set"
    )
    parser.add_argument("--random_state", type=int, default=42, help="Seed")
    parser.add_argument(
        "--model_path",
        type=str,
        default="model.joblib",
        help="Chemin de sauvegarde du modèle",
    )
    parser.add_argument(
        "--preprocessor_path",
        type=str,
        default="preprocessor.joblib",
        help="Chemin de sauvegarde du préprocesseur",
    )
    parser.add_argument(
        "--load",
        action="store_true",
        help="Charger un modèle déjà entraîné au lieu de le réentraîner",
    )

    args = parser.parse_args()

    print("=== DÉBUT DU PIPELINE ===\n")

    # 1. Préparation des données
    X_train, X_test, y_train, y_test, preprocessor, feature_names = prepare_data(
        file_path=args.data, test_size=args.test_size, random_state=args.random_state
    )

    if args.load:
        # Charger un modèle existant
        model, preprocessor = load_model(args.model_path, args.preprocessor_path)
    else:
        # 2. Entraînement
        model = train_model(X_train, y_train, random_state=args.random_state)

        # 3. Évaluation
        evaluate_model(model, X_test, y_test)

        # 4. Sauvegarde
        save_model(model, preprocessor, args.model_path, args.preprocessor_path)

    print("\n=== PIPELINE TERMINÉ AVEC SUCCÈS ===")


if __name__ == "__main__":
    main()
