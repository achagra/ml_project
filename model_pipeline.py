"""
model_pipeline.py
Pipeline modulaire pour la classification de réadmission (diabetic_data.csv)
"""

import pandas as pd
import joblib
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.metrics import (
    roc_auc_score,
    precision_score,
    recall_score,
    classification_report,
    confusion_matrix,
)
from xgboost import XGBClassifier
import warnings

warnings.filterwarnings("ignore")


def prepare_data(
    file_path: str = "diabetic_data.csv", test_size: float = 0.2, random_state: int = 42
):
    """
    Charge et prétraite les données.

    Returns:
        X_train, X_test, y_train, y_test, preprocessor, feature_names
    """
    # Chargement
    df = pd.read_csv(file_path, na_values=["?"], keep_default_na=False)
    print(f"Dimensions initiales : {df.shape}")

    # Nettoyage de base
    # Suppression des colonnes inutiles ou trop manquantes
    drop_cols = [
        "encounter_id",
        "patient_nbr",
        "weight",
        "payer_code",
        "medical_specialty",
        "examide",
        "citoglipton",
    ]
    df = df.drop(columns=[c for c in drop_cols if c in df.columns], errors="ignore")

    # Cible binaire : readmitted → 1 si <30 ou >30, 0 sinon (NO)
    df["readmitted"] = df["readmitted"].apply(lambda x: 0 if x == "NO" else 1)

    # Séparation features / target
    X = df.drop(columns=["readmitted"])
    y = df["readmitted"]

    # Identification des colonnes numériques et catégorielles
    numerical_cols = X.select_dtypes(include=["int64", "float64"]).columns.tolist()
    categorical_cols = X.select_dtypes(include=["object"]).columns.tolist()

    # Préprocesseur
    preprocessor = ColumnTransformer(
        transformers=[
            ("num", StandardScaler(), numerical_cols),
            (
                "cat",
                OneHotEncoder(handle_unknown="ignore", sparse_output=False),
                categorical_cols,
            ),
        ]
    )

    # Split
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=random_state, stratify=y
    )

    # Fit + transform
    X_train_processed = preprocessor.fit_transform(X_train)
    X_test_processed = preprocessor.transform(X_test)

    # Noms des features après OneHot
    cat_feature_names = preprocessor.named_transformers_["cat"].get_feature_names_out(
        categorical_cols
    )
    feature_names = numerical_cols + list(cat_feature_names)

    print(f"X_train shape après prétraitement : {X_train_processed.shape}")
    return (
        X_train_processed,
        X_test_processed,
        y_train,
        y_test,
        preprocessor,
        feature_names,
    )


def train_model(X_train, y_train, random_state: int = 42):
    """
    Entraîne un modèle XGBoost.
    """
    model = XGBClassifier(
        n_estimators=200,
        max_depth=6,
        learning_rate=0.1,
        subsample=0.8,
        colsample_bytree=0.8,
        random_state=random_state,
        eval_metric="logloss",
        n_jobs=-1,
    )
    model.fit(X_train, y_train)
    print("Modèle XGBoost entraîné avec succès.")
    return model


def evaluate_model(model, X_test, y_test):
    """
    Évalue le modèle et affiche les métriques principales.
    """
    y_pred = model.predict(X_test)
    y_proba = model.predict_proba(X_test)[:, 1]

    auc = roc_auc_score(y_test, y_proba)
    precision = precision_score(y_test, y_pred)
    recall = recall_score(y_test, y_pred)

    print("\n===== ÉVALUATION =====")
    print(f"AUC             : {auc:.4f}")
    print(f"Précision (1)    : {precision:.4f}")
    print(f"Rappel (1)       : {recall:.4f}")
    print("\nClassification Report :")
    print(classification_report(y_test, y_pred))
    print("\nMatrice de confusion :")
    print(confusion_matrix(y_test, y_pred))

    return {"auc": auc, "precision": precision, "recall": recall}


def save_model(
    model,
    preprocessor,
    model_path: str = "model.joblib",
    preprocessor_path: str = "preprocessor.joblib",
):
    """
    Sauvegarde le modèle et le préprocesseur avec joblib (extension .joblib).
    """
    joblib.dump(model, model_path)
    joblib.dump(preprocessor, preprocessor_path)
    print(f"Modèle sauvegardé → {model_path}")
    print(f"Préprocesseur sauvegardé → {preprocessor_path}")


def load_model(
    model_path: str = "model.joblib", preprocessor_path: str = "preprocessor.joblib"
):
    """
    Charge un modèle et un préprocesseur sauvegardés (extension .joblib).
    """
    model = joblib.load(model_path)
    preprocessor = joblib.load(preprocessor_path)
    print("Modèle et préprocesseur chargés avec succès.")
    return model, preprocessor
